// Public, read-only production review. --record also captures a silent walkthrough.
import assert from 'node:assert/strict';
import {mkdirSync,renameSync} from 'node:fs';
import {chromium} from 'playwright';
import {generateMatch,atTime} from '../src/footballEngine.ts';
const record=process.argv.includes('--record');
const target=process.env.TACTICLENS_URL??'https://cookiesgobrr.github.io/tacticlens-live/';
const directory=new URL('../test-results/production/',import.meta.url).pathname;
mkdirSync(directory,{recursive:true});
const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']}: {})});
const context=await browser.newContext({viewport:{width:1440,height:1000},...(record?{recordVideo:{dir:directory,size:{width:1440,height:1000}}}:{})});
const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
const linger=async ms=>{if(record)await page.waitForTimeout(ms)};
const showPitch=()=>page.locator('.new-pitchwrap').scrollIntoViewIfNeeded();
try{
  await page.goto(target+'?seed=82');
  await page.locator('.new-pitch [data-player-id]').first().waitFor();
  assert.equal(await page.locator('.new-pitch [data-player-id]').count(),22);
  const timeline=page.getByRole('slider',{name:'Match timeline'});
  await page.getByRole('button',{name:'Play',exact:true}).click();await linger(7000);
  await page.getByRole('button',{name:'3D studio',exact:true}).click();
  await page.locator('.new-pitch3d canvas').waitFor();await linger(7000);
  await page.getByRole('combobox',{name:'3D camera'}).selectOption('tactical');await linger(4000);
  await page.getByRole('button',{name:'Pause',exact:true}).click();
  await timeline.fill('2343.75');assert.ok((await page.locator('.new-score').innerText()).includes('0 : 2'));await linger(5000);
  await timeline.fill('3010');assert.ok((await page.locator('.new-score').innerText()).includes('1 : 2'));await linger(4000);
  await timeline.fill('4585.25');assert.ok((await page.locator('.new-score').innerText()).includes('2 : 2'));await linger(4000);
  await timeline.fill('4676.25');await page.getByRole('button',{name:'Play',exact:true}).click();
  await page.waitForFunction(()=>Number(document.querySelector('input[aria-label="Match timeline"]').value)>=4680.5);
  await page.getByRole('button',{name:'Pause',exact:true}).click();
  assert.ok((await page.locator('.new-score').innerText()).includes('3 : 2'));await linger(4000);await timeline.fill('4685');
  const moment=page.getByTestId('foundry-moment');await moment.waitFor();await moment.scrollIntoViewIfNeeded();
  assert.equal(+(await moment.getAttribute('data-moment-time')),4680.25);
  assert.ok((await moment.innerText()).includes('Evidence at 78:00'));await linger(5000);
  await page.getByRole('button',{name:'Analyst',exact:true}).click();
  assert.ok((await moment.innerText()).includes('15.2% synthetic xG'));await linger(5000);
  await page.getByRole('button',{name:'Club supporter',exact:true}).click();
  await page.getByLabel('Follow team',{exact:true}).selectOption('1');await moment.scrollIntoViewIfNeeded();
  assert.ok((await moment.innerText()).includes('Southbridge supporters'));await linger(4000);
  await page.getByLabel('Track a player',{exact:true}).selectOption('9');
  await page.getByRole('button',{name:'Player',exact:true}).click();await moment.scrollIntoViewIfNeeded();
  assert.ok((await moment.innerText()).includes('S. Grant has 3 goals'));await linger(4000);
  await page.getByRole('button',{name:'Fan',exact:true}).click();
  await page.getByText('Agent trace, all evidence & broadcast exports',{exact:true}).click();
  assert.equal(await page.locator('.new-ai-stage').count(),3);await linger(6000);
  await page.screenshot({path:directory+'foundry-production.png',fullPage:true});
  const jsonDownload=page.waitForEvent('download');await page.getByRole('button',{name:'Export AI moment JSON',exact:true}).click();
  await (await jsonDownload).saveAs(directory+'SIM-82-AI-moment.json');
  const vttDownload=page.waitForEvent('download');await page.getByRole('button',{name:'Export AI broadcast VTT',exact:true}).click();
  await (await vttDownload).saveAs(directory+'SIM-82-AI-broadcast.vtt');await linger(4000);
  await moment.getByRole('button').filter({hasText:'SIM-82-01628'}).first().click();
  const match=generateMatch(82),shot=match.events.find(e=>e.id==='SIM-82-01628');
  assert.equal(+(await timeline.inputValue()),shot.time);await showPitch();await linger(5000);
  await timeline.fill('4680');assert.ok((await page.locator('.new-score').innerText()).includes('2 : 2'));
  assert.equal(+(await page.getByTestId('foundry-moment').getAttribute('data-moment-time')),4585.25);await linger(3000);
  await timeline.fill('5400');await page.getByRole('combobox',{name:'3D camera'}).selectOption('broadcast');
  await showPitch();
  await page.waitForFunction(()=>JSON.parse(document.querySelector('.new-pitch3d canvas').dataset.renderedFrame??'{}').time===5400);
  const mesh=JSON.parse(await page.locator('.new-pitch3d canvas').getAttribute('data-rendered-frame'));
  const expected=atTime(match,5400);
  for(let i=0;i<22;i++)assert.ok(Math.hypot(mesh.people[i].x-expected.people[i].x,mesh.people[i].y-expected.people[i].y)<1e-5);
  await page.screenshot({path:directory+'3d-production.png',fullPage:true});await linger(6000);
  assert.deepEqual(errors,[]);
  const video=page.video();await context.close();
  if(record&&video)renameSync(await video.path(),directory+'demo-silent.webm');
  const mobile=await browser.newPage({viewport:{width:390,height:844}});
  await mobile.goto(target+'?seed=82');await mobile.getByRole('slider',{name:'Match timeline'}).fill('4680.25');
  await mobile.getByTestId('foundry-moment').waitFor();
  assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await mobile.screenshot({path:directory+'mobile-production.png',fullPage:true});await mobile.close();
  console.log(`Production verified: actual seed 82 Foundry, audiences, downloads, pre-winner rewind, 3D coordinate parity and mobile. ${record?'Silent demonstration saved.':''}`);
}finally{await browser.close();}
